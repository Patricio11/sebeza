-- Role blueprints (docs/ROLE_BLUEPRINTS_PLAN.md, 2026-08-28).
--
-- 1. profession_skill_blueprints: what a role's skill set looks like, in
--    three tiers (core / expected / next_level) with named tracks for the
--    next level. Admin-managed on /admin/blueprints; the starter catalogue
--    in lib/blueprints/catalogue.ts is imported from there. Seekers read
--    the table; an empty profession falls back to the starter constant.
-- 2. The skills the blueprints need that the taxonomy did not have.
--    ON CONFLICT DO NOTHING so admin edits to existing rows are kept.

CREATE TABLE IF NOT EXISTS profession_skill_blueprints (
  profession_slug text NOT NULL,
  skill_slug      text NOT NULL REFERENCES skills(slug),
  tier            text NOT NULL CHECK (tier IN ('core', 'expected', 'next_level')),
  track           text,
  prove_it        text,
  source          text NOT NULL DEFAULT 'seed',
  updated_at      timestamp NOT NULL DEFAULT now(),
  updated_by_user_id text,
  PRIMARY KEY (profession_slug, skill_slug)
);

CREATE INDEX IF NOT EXISTS profession_skill_blueprints_skill_idx
  ON profession_skill_blueprints (skill_slug);

